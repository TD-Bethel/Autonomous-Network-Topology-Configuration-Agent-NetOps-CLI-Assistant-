import re
from pathlib import Path

from netops.design.ipam import NetworkDesign, design_network
from netops.ir.v1.intent import NetworkIntent
from netops.render.ios import render_ios
from netops.verify import verify_ios

EXAMPLE = Path(__file__).parents[1] / "examples" / "campus.yaml"
GOLDEN = Path(__file__).parent / "golden" / "campus_ios.cfg"


def make_pipeline() -> tuple[NetworkDesign, str]:
    import yaml

    raw = yaml.safe_load(EXAMPLE.read_text(encoding="utf-8"))
    intent = NetworkIntent.model_validate(raw)
    design = design_network(intent)
    return design, render_ios(design)


def test_golden_render_and_verification_pass() -> None:
    design, config = make_pipeline()

    assert config == render_ios(design) == GOLDEN.read_text(encoding="utf-8")
    assert "! Generated by netops-compiler. Review before use." in config
    assert verify_ios(config, design) == []


def test_missing_svi_line_is_a_blocker() -> None:
    design, config = make_pipeline()
    config = config.replace(" no shutdown\n", "", 1)

    findings = verify_ios(config, design)

    assert any(finding.rule_id == "IOS-MISSING-EXPECTED-STATE" for finding in findings)
    assert all(finding.severity == "blocker" for finding in findings)


def test_unplanned_vlan_is_a_blocker() -> None:
    design, config = make_pipeline()
    findings = verify_ios(config + "\nvlan 4094\n name surprise\n!\n", design)

    assert any(finding.rule_id == "IOS-UNEXPECTED-VLAN" for finding in findings)


def test_missing_dhcp_pool_is_a_blocker() -> None:
    design, config = make_pipeline()
    config = re.sub(r"(?ms)^ip dhcp pool hq_guest\n.*?^!\n", "", config, count=1)

    findings = verify_ios(config, design)

    assert any(finding.rule_id == "IOS-MISSING-DHCP-STATE" for finding in findings)


