def test_unplanned_dhcp_pool_is_a_blocker() -> None:
    design, config = make_pipeline()
    config += "\nip dhcp pool unplanned\n network 198.51.100.0 255.255.255.0\n!\n"

    findings = verify_ios(config, design)

    assert any(finding.rule_id == "IOS-UNEXPECTED-DHCP-POOL" for finding in findings)
